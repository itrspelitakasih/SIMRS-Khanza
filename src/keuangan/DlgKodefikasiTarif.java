    private static void lebar(widget.Table t, int... w) {
        t.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_OFF);
        for (int i = 0; i < w.length; i++) t.getColumnModel().getColumn(i).setPreferredWidth(w[i]);
    }

    private static String kunci(Aturan a) {
        return a.jenis.name() + "|" + a.kelas;
    }

    private boolean perbaruiHarga() {
        return ChkPerbarui.isEnabled() && ChkPerbarui.isSelected();
    }

    private void muatPilihan() {
        kodeTujuan.add("");
        CmbTujuan.addItem("- Pilih Jenis Bayar -");
        kodeHarga.add("");
        CmbHarga.addItem("- Sama dengan sumber tarif -");
        isiCombo("select kd_pj,png_jawab from penjab where status='1' and kd_pj<>'-' order by png_jawab", kodeTujuan, CmbTujuan);
        isiCombo("select p.kd_pj,p.png_jawab from penjab p where p.status='1' and p.kd_pj<>'-' and (exists(select 1 from jns_perawatan_lab a where a.kd_pj=p.kd_pj and a.status='1') "
                + "or exists(select 1 from jns_perawatan_radiologi b where b.kd_pj=p.kd_pj and b.status='1') "
                + "or exists(select 1 from jns_perawatan_inap c where c.kd_pj=p.kd_pj and c.status='1')) order by (p.png_jawab='Cash') desc,p.png_jawab", kodeSumber, CmbSumber);
        // pilihan harga = jenis bayar yang sama dengan pilihan sumber tarif
        for (int i = 0; i < kodeSumber.size(); i++) {
            kodeHarga.add(kodeSumber.get(i));
            CmbHarga.addItem(CmbSumber.getItemAt(i));
        }
    }

    private void isiCombo(String sql, List<String> kode, widget.ComboBox cmb) {
        try (PreparedStatement ps = koneksi.prepareStatement(sql); ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                kode.add(rs.getString(1));
                cmb.addItem(rs.getString(2) + " [" + rs.getString(1) + "]");
            }
        } catch (Exception e) {
            System.out.println("Notif Kodefikasi Tarif : " + e.getMessage());
        }
    }

    /** Isi awal jenis bayar yang baru disimpan / dipilih di form Penanggung. */
    public void setJenisBayar(String kdPj) {
        int i = kodeTujuan.indexOf(kdPj);
        memuat = true;
        CmbTujuan.setSelectedIndex(Math.max(i, 0));
        TAwalan.setText(i > 0 ? kdPj : "");
        memuat = false;
        basi();
    }

    /** Jenis bayar / sumber / awalan berubah: pratinjau lama dan ubahan per baris tidak berlaku. */
    private void basi() {
        centangUser.clear();
        awalanUser.clear();
        tidakDisalin.clear();
        kosongkan();
    }

    private void kosongkan() {
        data = null;
        aturan = new ArrayList<>();
        pratinjau = new ArrayList<>();
        memuat = true;
        tabAturan.setRowCount(0);
        tabPratinjau.setRowCount(0);
        memuat = false;
        LPeringatan.setText("");
        salahAwalan = "";
        LStatus.setText(" Isi Awalan Kode (mis. BPJS) lalu klik Tampilkan.");
    }

    private void tampilkan() {
        int t = CmbTujuan.getSelectedIndex(), s = CmbSumber.getSelectedIndex();
        String awalan = TAwalan.getText().trim().toUpperCase(Locale.ROOT);
        if (t <= 0 || s < 0) { JOptionPane.showMessageDialog(this, "Pilih Jenis Bayar Baru dan sumber tarifnya terlebih dahulu."); return; }
        if (!awalan.matches("[A-Z0-9]{1,7}")) { JOptionPane.showMessageDialog(this, "Awalan Kode harus 1-7 huruf/angka, contoh: BPJS."); return; }
        basi();
        TAwalan.setText(awalan);
        awalanDipakai = awalan;
        bacaData();
    }

    private void bacaData() {
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            sumberDipakai = kodeSumber.get(CmbSumber.getSelectedIndex());
            hargaDipakai = kodeHarga.get(Math.max(CmbHarga.getSelectedIndex(), 0));
            data = KodefikasiTarif.muat(kodeTujuan.get(CmbTujuan.getSelectedIndex()), sumberDipakai, hargaDipakai);
            tampilAturan();
        } catch (Exception e) {
            kosongkan();
            JOptionPane.showMessageDialog(this, "Gagal menampilkan tarif: " + e.getMessage());
        }
        setCursor(Cursor.getDefaultCursor());
    }

    /** Aturan sesuai Filter Kelas; tanpa membaca ulang tarif. */
    private void tampilAturan() {
        if (tbAturan.isEditing()) tbAturan.getCellEditor().cancelCellEditing();
        if (tbPratinjau.isEditing()) tbPratinjau.getCellEditor().cancelCellEditing();
        String filter = String.valueOf(CmbKelas.getSelectedItem());
        boolean perbarui = perbaruiHarga();
        List<Aturan> tampil = new ArrayList<>();
        for (Aturan a : KodefikasiTarif.aturanAwal(data, awalanDipakai, izin, perbarui)) {
            if (!KodefikasiTarif.masukFilter(filter, a.kelas)) continue;
            if (izin.contains(a.jenis) && centangUser.containsKey(kunci(a))) a.pilih = centangUser.get(kunci(a));
            if (awalanUser.containsKey(kunci(a))) a.awalan = awalanUser.get(kunci(a));
            tampil.add(a);
        }
        aturan = tampil;
        List<String> bocor = new ArrayList<>();
        memuat = true;
        tabAturan.setRowCount(0);
        for (Aturan a : aturan) {
            List<String> ket = new ArrayList<>();
            if (!izin.contains(a.jenis)) ket.add("Anda tidak punya hak akses tarif ini");
            else {
                if (a.baru > 0 && !data.perJenisBayar(a.jenis)) {
                    ket.add("Akan tampil untuk pasien SEMUA jenis bayar (Set Tarif = No)");
                    if (!bocor.contains(a.jenis.nama)) bocor.add(a.jenis.nama);
                }
                if (a.baru == 0) ket.add("Semua sudah ada");
                if (a.ubahHarga > 0 && !perbarui) ket.add("harga beda, centang Perbarui harga");
                if (a.tanpaHarga > 0) ket.add(a.tanpaHarga + " tarif lama tanpa padanan harga, tetap");
            }
            tabAturan.addRow(new Object[]{a.pilih, a.jenis.nama, a.kelas, a.awalan, a.awalan + "-0001", a.baru, a.ubahHarga, a.sudahAda, String.join("; ", ket)});
        }
        memuat = false;
        LPeringatan.setText(bocor.isEmpty() ? "" : String.join(", ", bocor) + " tidak dicentang: Set Tarif cara bayar = No, hasil salinan akan tampil dobel di pencarian semua pasien.");
        susun();
    }

    private void ubahAturan(int r, int kolom) {
        if (memuat || data == null || r < 0 || r >= aturan.size() || (kolom != 0 && kolom != 3)) return;
        Aturan a = aturan.get(r);
        if (kolom == 0) {
            a.pilih = Boolean.TRUE.equals(tabAturan.getValueAt(r, 0));
            centangUser.put(kunci(a), a.pilih);
        } else {
            a.awalan = String.valueOf(tabAturan.getValueAt(r, 3)).trim().toUpperCase(Locale.ROOT);
            awalanUser.put(kunci(a), a.awalan);
        }
        susun();
    }

    private void ubahPratinjau(int r, int kolom) {
        if (memuat || data == null || r < 0 || r >= pratinjau.size() || kolom != 0) return;
        if (Boolean.TRUE.equals(tabPratinjau.getValueAt(r, 0))) tidakDisalin.remove(pratinjau.get(r).kunci);
        else tidakDisalin.add(pratinjau.get(r).kunci);
        susun();
    }

    /** Klik kanan pratinjau: hanya baris yang sedang tampil. */
    private void pilihSemuaPratinjau(boolean pilih) {
        if (data == null || pratinjau.isEmpty()) return;
        if (tbPratinjau.isEditing()) tbPratinjau.getCellEditor().cancelCellEditing();
        for (Baris b : pratinjau) {
            if (pilih) tidakDisalin.remove(b.kunci); else tidakDisalin.add(b.kunci);
        }
        susun();
    }

    /** Klik kanan tabel jenis tarif/kelas: Pilih Semua hanya baris yang ada pekerjaannya dan boleh diubah user. */
    private void pilihSemuaAturan(boolean pilih) {
        if (data == null) return;
        if (tbAturan.isEditing()) tbAturan.getCellEditor().stopCellEditing();
        memuat = true;
        for (int i = 0; i < aturan.size(); i++) {
            Aturan a = aturan.get(i);
            if (!izin.contains(a.jenis)) continue;
            a.pilih = pilih && (a.baru > 0 || (perbaruiHarga() && a.ubahHarga > 0));
            centangUser.put(kunci(a), a.pilih);
            tabAturan.setValueAt(a.pilih, i, 0);
        }
        memuat = false;
        susun();
    }

    private static String angkaPilih(int dipilih, int total, boolean tampil) {
        return tampil && dipilih != total ? dipilih + " / " + total : String.valueOf(total);
    }

    private void susun() {
        salahAwalan = "";
        try {
            pratinjau = KodefikasiTarif.susun(data, aturan, perbaruiHarga(), tidakDisalin);
        } catch (Exception e) {
            salahAwalan = e.getMessage();
            pratinjau = new ArrayList<>();
            isiPratinjau();
            LStatus.setText(" Perbaiki awalan kode.");
            JOptionPane.showMessageDialog(this, e.getMessage(), "Awalan Kode", JOptionPane.WARNING_MESSAGE);
            return;
        }
        isiPratinjau();
    }

    private void isiPratinjau() {
        memuat = true;
        // jumlah sama = cukup perbarui sel, posisi gulir tidak lompat saat mencentang
        boolean bangun = tabPratinjau.getRowCount() != pratinjau.size();
        if (bangun) tabPratinjau.setRowCount(0);
        Map<String, int[]> dipilih = new HashMap<>(); // {baru, ubah}
        Map<String, String> kodePertama = new HashMap<>();
        int nomorBaris = -1, centang = 0;
        int baru = 0, ubah = 0, tanpaHarga = 0, nol = 0;
        for (Baris b : pratinjau) {
            String harga;
            nomorBaris++;
            if (b.pilih) {
                centang++;
                String g = b.jenis.name() + "|" + b.kelas;
                dipilih.computeIfAbsent(g, k -> new int[2])[b.ubah ? 1 : 0]++;
                if (b.ubah) ubah++;
                else {
                    baru++;
                    kodePertama.putIfAbsent(g, b.kode);
                    if (b.tarifNol) nol++;
                }
            }
            if (!b.kodeHarga.equals("")) harga = b.kodeHarga;
            else if (!b.ketHarga.equals("")) { harga = "tetap: " + b.ketHarga; if (b.pilih) tanpaHarga++; }
            else harga = b.sumber;
            Object[] sel = {b.pilih, b.ubah ? "Ubah Harga" : "Baru", b.jenis.nama, b.kode.equals("") ? "-" : b.kode, b.nama, b.kelas, b.ubah ? "-" : b.sumber, b.tarif, harga};
            if (bangun) tabPratinjau.addRow(sel);
            else
                for (int k = 0; k < sel.length; k++)
                    if (!sel[k].equals(tabPratinjau.getValueAt(nomorBaris, k))) tabPratinjau.setValueAt(sel[k], nomorBaris, k);
        }
        // contoh = kode pertama yang benar-benar dibuat (nomor melanjutkan yang sudah ada)
        for (int i = 0; i < aturan.size() && i < tabAturan.getRowCount(); i++) {
            Aturan a = aturan.get(i);
            String contoh = a.baru > 0 ? a.awalan + "-0001" : "-";
            int[] n = dipilih.getOrDefault(kunci(a), new int[2]);
            if (a.pilih && a.baru > 0 && salahAwalan.equals("")) contoh = kodePertama.getOrDefault(kunci(a), "-");
            boolean tampil = a.pilih && salahAwalan.equals("");
            tabAturan.setValueAt(contoh, i, 4);
            tabAturan.setValueAt(angkaPilih(n[0], a.baru, tampil), i, 5);
            tabAturan.setValueAt(angkaPilih(n[1], a.ubahHarga, tampil && perbaruiHarga()), i, 6);
        }
        memuat = false;
        if (pratinjau.isEmpty()) {
            LStatus.setText(" Tidak ada yang disalin untuk pilihan dan filter kelas ini. Klik Salin untuk melihat alasannya.");
            LStatus.setToolTipText(null);
            return;
        }
        if (centang == 0) {
            LStatus.setText(" 0 dari " + pratinjau.size() + " dicentang. Klik kanan tabel pratinjau > Pilih Semua.");
            LStatus.setToolTipText(null);
            return;
        }
        String s = " " + (centang < pratinjau.size() ? centang + " dari " + pratinjau.size() + " dicentang: " : "") + baru + " tarif baru";
        if (ubah > 0) s += ", " + ubah + " harga diubah";
        if (tanpaHarga > 0) s += ", " + tanpaHarga + " tanpa padanan harga (pakai harga sumber tarif)";
        if (nol > 0) s += ", " + nol + " bertarif Rp 0";
        LStatus.setText(s + ". Periksa, lalu Salin.");
        LStatus.setToolTipText(s);
    }

    private void salin() {
        if (tbAturan.isEditing()) tbAturan.getCellEditor().stopCellEditing();
        if (tbPratinjau.isEditing()) tbPratinjau.getCellEditor().stopCellEditing();
        if (data == null) {
            JOptionPane.showMessageDialog(this, "Klik Tampilkan dulu, periksa pratinjau, lalu Salin.");
            return;
        }
        if (pratinjau.isEmpty()) {
            JOptionPane.showMessageDialog(this, alasanKosong(), "Tidak ada yang disalin", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        int tidak = 0;
        for (Baris b : pratinjau) if (!b.pilih) tidak++;
        if (tidak == pratinjau.size()) {
            JOptionPane.showMessageDialog(this, "Belum ada tarif yang dicentang.\nCentang kolom P di tabel pratinjau, atau klik kanan > Pilih Semua.");
            return;
        }
        int baru = 0, labBaru = 0, ubah = 0, tanpaHarga = 0;
        StringBuilder rinci = new StringBuilder();
        boolean bocor = false;
        for (Jenis j : Jenis.values()) {
            int b1 = 0, u1 = 0;
            String awal = "";
            for (Baris b : pratinjau) {
                if (b.jenis != j || !b.pilih) continue;
                if (b.ubah) { u1++; continue; }
                if (!b.ketHarga.equals("")) tanpaHarga++;
                if (b1++ == 0) awal = b.kode;
            }
            baru += b1;
            ubah += u1;
            if (j == Jenis.LAB) labBaru = b1;
            if (b1 + u1 == 0) continue;
            rinci.append("\n- ").append(j.nama).append(": ");
            if (b1 > 0) rinci.append(b1).append(" tarif baru, mulai ").append(awal);
            if (u1 > 0) rinci.append(b1 > 0 ? "; " : "").append(u1).append(" harga diubah");
            if (b1 > 0 && !data.perJenisBayar(j)) bocor = true;
        }
        StringBuilder s = new StringBuilder("Proses untuk " + CmbTujuan.getSelectedItem() + " (" + CmbKelas.getSelectedItem() + ")?\n");
        s.append(rinci);
        if (tidak > 0) s.append("\n\n").append(tidak).append(" baris tidak dicentang, tidak diproses.");
        s.append("\n\nHarga: ").append(hargaDipakai.equals("") ? "sama dengan sumber tarif." : "dari " + CmbHarga.getSelectedItem() + ".");
        if (labBaru > 0) s.append("\n\nTemplate hasil lab tidak ikut disalin, isi sendiri untuk ").append(labBaru).append(" tarif lab baru.");
        if (tanpaHarga > 0) s.append("\n").append(tanpaHarga).append(" tarif baru tanpa padanan memakai harga sumber tarif.");
        if (ubah > 0) s.append("\n\nPERHATIAN: ").append(ubah).append(" harga tarif yang sudah ada akan DITIMPA.\n")
                .append("Transaksi yang sudah diinput tetap harga lama; permintaan lab/radiologi yang\n")
                .append("belum diproses (termasuk dari Paket Tindakan) akan memakai harga baru.");
        if (bocor) s.append("\n\nPERHATIAN: ada jenis tarif dengan Set Tarif cara bayar = No.\n")
                .append("Tarif baru itu akan tampil di pencarian pasien SEMUA jenis bayar (nama jadi dobel).");
        s.append("\n\nTidak bisa dibatalkan sekaligus.");
        Object[] tombol = {"Salin", "Batal"};
        if (JOptionPane.showOptionDialog(this, s.toString(), "Kodefikasi & Salin Tarif", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE, null, tombol, tombol[1]) != 0) return;
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            int[] n = KodefikasiTarif.simpan(data.tujuan, sumberDipakai, hargaDipakai, aturan, pratinjau,
                    ChkMapping.isSelected(), perbaruiHarga());
            setCursor(Cursor.getDefaultCursor());
            basi();
            LStatus.setText(" Selesai: " + n[0] + " tarif dibuat, " + n[2] + " harga diubah.");
            JOptionPane.showMessageDialog(this, "Berhasil:\n- " + n[0] + " tarif baru\n- " + n[2] + " harga diubah\n- " + n[1] + " mapping SatuSehat radiologi"
                    + (labBaru > 0 ? "\n\nTemplate hasil " + labBaru + " tarif lab baru belum ada, silakan isi sendiri." : ""));
        } catch (Exception e) {
            setCursor(Cursor.getDefaultCursor());
            JOptionPane.showMessageDialog(this, "Gagal, tidak ada tarif yang dibuat atau diubah.\n" + e.getMessage());
        }
    }

    /** Kenapa pratinjau kosong, dan apa yang bisa dipilih. */
    private String alasanKosong() {
        if (!salahAwalan.equals("")) return "Awalan kode perlu diperbaiki.\n" + salahAwalan;
        String filter = String.valueOf(CmbKelas.getSelectedItem());
        boolean perbarui = perbaruiHarga();
        StringBuilder s = new StringBuilder("Tidak ada yang perlu diproses untuk ").append(CmbTujuan.getSelectedItem()).append(", ").append(filter).append(".\n");
        boolean belumCentang = false, perluPerbarui = false, tanpaAkses = false;
        for (Aturan a : aturan) {
            s.append("\n- ").append(a.jenis.nama).append(" ").append(a.kelas).append(": sumber punya ").append(a.baru + a.sudahAda)
                    .append(" tarif, ").append(a.sudahAda).append(" sudah ada");
            if (a.baru > 0) s.append(", ").append(a.baru).append(" baru");
            if (a.ubahHarga > 0) s.append(", ").append(a.ubahHarga).append(" beda harga");
            if (a.baru + a.ubahHarga == 0) continue;
            if (!izin.contains(a.jenis)) { tanpaAkses = true; continue; }
            if (a.ubahHarga > 0 && !perbarui) perluPerbarui = true;
            if (!a.pilih && (a.baru > 0 || (perbarui && a.ubahHarga > 0))) belumCentang = true;
        }
        if (aturan.isEmpty()) s.append("\nSumber tidak punya tarif aktif di kelas ini.");

        List<String> saran = new ArrayList<>(), kelasLain = new ArrayList<>();
        if (belumCentang) saran.add("Centang kolom P pada baris yang mau disalin.");
        if (perluPerbarui) saran.add(ChkPerbarui.isEnabled() ? "Centang Perbarui juga harga tarif yang sudah ada." : "Pilih Salin Harga Dari, lalu centang Perbarui.");
        if (tanpaAkses) saran.add("Sebagian butuh hak akses tarif yang belum Anda miliki.");
        if (!filter.equals(KodefikasiTarif.FILTER_KELAS[0]))
            for (Aturan a : KodefikasiTarif.aturanAwal(data, awalanDipakai, izin, perbarui))
                if (a.pilih && !KodefikasiTarif.masukFilter(filter, a.kelas) && !kelasLain.contains(a.kelas)) kelasLain.add(a.kelas);
        if (!kelasLain.isEmpty()) saran.add("Masih ada yang bisa diproses di " + String.join(", ", kelasLain) + ": ubah Filter Kelas.");
        if (!String.valueOf(CmbSumber.getSelectedItem()).startsWith("Cash ["))
            saran.add("Bila daftar tarif sumber kurang lengkap, pilih Salin Tarif Dari = Cash, lalu Tampilkan.");
        if (!saran.isEmpty()) s.append("\n\nYang bisa dilakukan:\n- ").append(String.join("\n- ", saran));
        return s.toString();
    }
