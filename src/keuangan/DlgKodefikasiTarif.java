    private void CmbHargaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CmbHargaActionPerformed
        if (memuat) return;
        boolean ada = CmbHarga.getSelectedIndex() > 0;
        ChkPerbarui.setEnabled(ada);
        if (!ada) ChkPerbarui.setSelected(false);
        if (data != null) bacaData();
    }//GEN-LAST:event_CmbHargaActionPerformed

    private void TAwalanKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TAwalanKeyReleased
        if (evt.getKeyCode() == KeyEvent.VK_ENTER) tampilkan();
        else if (data != null && !TAwalan.getText().trim().equalsIgnoreCase(awalanDipakai)) basi();
    }//GEN-LAST:event_TAwalanKeyReleased

    private void ChkPerbaruiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ChkPerbaruiActionPerformed
        if (data == null) return;
        // baris yang punya perubahan harga mengikuti pilihan ini lagi
        for (Aturan a : aturan) if (a.ubahHarga > 0) centangUser.remove(kunci(a));
        tampilAturan();
    }//GEN-LAST:event_ChkPerbaruiActionPerformed

