    /** Tampilkan popup di pojok kanan bawah area kerja bila belum tampil. */
    public void tampil(Rectangle area){
        if(!isVisible()){
            int tinggi=Math.min(getHeight(),area.height-20);
            setSize(getWidth(),tinggi);
            setLocation(area.x+area.width-getWidth()-10,area.y+area.height-tinggi-10);
        }
        setVisible(true);
        toFront();
        TPesan.requestFocus();
    }

    /** Jendela tanpa title bar: geser popup dengan menarik bingkai judul. */
    private void geserDenganBingkai(){
        MouseAdapter geser=new MouseAdapter(){
            private Point awal;
            @Override public void mousePressed(MouseEvent e){awal=e.getPoint();}
            @Override public void mouseDragged(MouseEvent e){
                if(awal!=null){
                    Point p=getLocation();
                    setLocation(p.x+e.getX()-awal.x,p.y+e.getY()-awal.y);
                }
            }
        };
        internalFrame1.addMouseListener(geser);
        internalFrame1.addMouseMotionListener(geser);
    }

    private void mulaiPercakapan(){
        ai=new AsistenAI();
        pesanTampil.clear();
        totalToken=0;
        modelTerakhir="";
        if(ai.siap()){
            tambah("info","Halo, saya Asisten AI. Silakan tanyakan apa saja (pertanyaan umum, bukan data pasien).");
        }else if(!ai.getSetting().aktif){
            tambah("info","Asisten AI sedang dinonaktifkan oleh admin.");
        }else{
            tambah("info",AsistenAI.pesanBelumDiisi(ai.getSetting().provider)+" Hubungi IT.");
        }
        tampilkanStatus();
        TPesan.setEnabled(ai.siap());
        BtnKirim.setEnabled(ai.siap());
    }

    private void kirim(){
        final String pesan=TPesan.getText().trim();
        if(sibuk||!ai.siap()){
            return;
        }
        if(pesan.equals("")){
            TPesan.requestFocus();
            return;
        }
        if(pesan.length()>20000){
            JOptionPane.showMessageDialog(this,"Pesan terlalu panjang, maksimal 20.000 karakter.");
            return;
        }
        TPesan.setText("");
        tambah("user",pesan);
        final String[] jawaban={"ai",""};
        pesanTampil.add(jawaban);
        setSibuk(true);
        final AsistenAI percakapan=ai;
        new SwingWorker<AsistenAI.Hasil,String>(){
            @Override
            protected AsistenAI.Hasil doInBackground(){
                return percakapan.kirim(pesan,kodeSaya,this::publish);
            }

            @Override
            protected void process(List<String> potongan){
                if(percakapan!=ai){
                    return;
                }
                StringBuilder sb=new StringBuilder(jawaban[1]);
                for(String p:potongan){
                    sb.append(p);
                }
                jawaban[1]=sb.toString();
                perluTampil=true;
            }

            @Override
            protected void done(){
                setSibuk(false);
                if(percakapan!=ai){
                    return;
                }
                AsistenAI.Hasil h;
                try {
                    h=get();
                } catch (InterruptedException|ExecutionException e) {
                    h=new AsistenAI.Hasil();
                    h.pesanGagal="Gagal : "+e.getMessage();
                }
                totalToken+=h.inputTokens+h.outputTokens;
                if(!h.model.equals("")){
                    modelTerakhir=h.model;
                }
                if(h.pesanGagal!=null){
                    // jawaban tidak masuk riwayat: hapus dari layar dan kembalikan pesan agar bisa dikirim ulang
                    pesanTampil.remove(jawaban);
                    tambah("info",h.pesanGagal);
                    if(TPesan.getText().trim().equals("")){
                        TPesan.setText(pesan);
                    }
                }else{
                    jawaban[1]=h.teks;
                    if(h.terpotong){
                        tambah("info","Jawaban terpotong karena mencapai batas Max Tokens.");
                    }
                    tampilkan();
                }
                tampilkanStatus();
                TPesan.requestFocus();
            }
        }.execute();
    }

    private void setSibuk(boolean b){
        sibuk=b;
        BtnKirim.setEnabled(!b);
        BtnBaru.setEnabled(!b);
        BtnSetting.setEnabled(!b);
        LblStatus.setText(b?"Asisten AI sedang menjawab...":LblStatus.getText());
    }

    private void tampilkanStatus(){
        LblStatus.setText("Model : "+(modelTerakhir.equals("")?ai.getSetting().model:modelTerakhir)+(totalToken>0?"   |   "+String.format("%,d",totalToken).replace(',','.')+" token":""));
    }

    private void tambah(String peran,String teks){
        pesanTampil.add(new String[]{peran,teks});
        tampilkan();
    }

    private void tampilkan(){
        StringBuilder sb=new StringBuilder();
        for(String[] p:pesanTampil){
            switch (p[0]) {
                case "user":
                    sb.append("<table width='100%' cellspacing='0' cellpadding='3'><tr><td align='right'>")
                      .append("<table cellspacing='0' cellpadding='6' bgcolor='#DCF8C6'><tr><td>")
                      .append(esc(p[1]).replace("\n","<br>"))
                      .append("</td></tr></table></td></tr></table>");
                    break;
                case "ai":
                    sb.append("<table width='100%' cellspacing='0' cellpadding='3'><tr><td align='left'>")
                      .append("<table cellspacing='0' cellpadding='6' bgcolor='#EEF2F7'><tr><td>")
                      .append("<span class='nama'>").append("Asisten AI").append("</span><br>")
                      .append(p[1].equals("")?"<span class='info'>mengetik...</span>":markdown(p[1]))
                      .append("</td></tr></table></td></tr></table>");
                    break;
                default:
                    sb.append("<p class='info'>").append(esc(p[1])).append("</p>");
                    break;
            }
        }
        TampilChat.setText("<html><head><style>body{font-family:Arial;font-size:11pt;color:#323232;margin:4px}"+
                ".nama{color:#6A3FB5;font-size:10pt}.info{color:#888888;font-size:10pt}"+
                "pre{font-family:Consolas,monospace;font-size:10pt;background-color:#F6F8FA;margin:4px 0px}"+
                "code{font-family:Consolas,monospace;color:#B3261E}</style></head><body>"+
                sb+"</body></html>");
        final JScrollBar bar=ScrollTampil.getVerticalScrollBar();
        SwingUtilities.invokeLater(() -> bar.setValue(bar.getMaximum()));
    }

    private static String esc(String s){
        return s.replace("&","&amp;").replace("<","&lt;").replace(">","&gt;").replace("\"","&quot;");
    }

    /** Markdown sederhana dari jawaban AI: blok kode, judul, daftar, tebal dan kode inline. */
    private static String markdown(String md){
        StringBuilder sb=new StringBuilder();
        boolean dalamKode=false;
        for(String baris:md.split("\n",-1)){
            if(baris.trim().startsWith("```")){
                sb.append(dalamKode?"</pre>":"<pre>");
                dalamKode=!dalamKode;
                continue;
            }
            if(dalamKode){
                sb.append(esc(baris)).append("\n");
                continue;
            }
            String t=baris.trim();
            if(t.matches("#{1,6} .*")){
                sb.append("<b>").append(inline(t.replaceFirst("#{1,6} ",""))).append("</b><br>");
            }else if(t.startsWith("- ")||t.startsWith("* ")){
                sb.append("&nbsp;&nbsp;&bull; ").append(inline(t.substring(2))).append("<br>");
            }else if(t.matches("-{3,}")){
                sb.append("<hr>");
            }else{
                sb.append(inline(baris)).append("<br>");
            }
        }
        if(dalamKode){
            sb.append("</pre>");
        }
        return sb.toString();
    }

    private static String inline(String s){
        return esc(s).replaceAll("`([^`]+)`","<code>$1</code>")
                .replaceAll("\\*\\*([^*]+)\\*\\*","<b>$1</b>");
    }
