    private void BtnBawaanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnBawaanActionPerformed
        if(aktif==null){
            return;
        }
        String tanya=aktif.induk==null
                ?"Kembalikan \""+aktif.judul+"\" ke teks bawaan program?\nUbahan yang tersimpan akan dihapus."
                :"Kembalikan \""+aktif.judul+"\" agar memakai template umum lagi?\nTeks khusus jenis surat ini akan dihapus.";
        if(JOptionPane.showConfirmDialog(this,tanya,"Konfirmasi",JOptionPane.YES_NO_OPTION)!=JOptionPane.YES_OPTION){
            return;
        }
        try {
            pesanWA.kembalikanBawaan(aktif);
            isiAwal=pesanWA.ambil(aktif);
            TIsi.setText(isiAwal);
            TIsi.setCaretPosition(0);
            perbaruiStatus();
        } catch (Exception e) {
            System.out.println("Notif : "+e);
            JOptionPane.showMessageDialog(this,"Gagal mengembalikan template:\n"+e.getMessage());
        }
    }//GEN-LAST:event_BtnBawaanActionPerformed

    private void CmbJenisSuratActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CmbJenisSuratActionPerformed
        if(gantiJenis||dipilih==null){
            return;
        }
        int idx=CmbJenisSurat.getSelectedIndex();
        if(idx==jenisLama){
            return;
        }
        if(!konfirmasiPerubahan()){
            // batal pindah, kembalikan pilihan jenis surat sebelumnya
            pilihJenis(jenisLama);
            return;
        }
        jenisLama=idx;
        muat(idx<=0?dipilih:pesanWA.suratJenis(pesanWA.JENIS_SURAT[idx-1]));
    }//GEN-LAST:event_CmbJenisSuratActionPerformed

