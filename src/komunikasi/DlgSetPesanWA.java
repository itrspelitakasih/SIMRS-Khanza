    private void tampil(){
        tabMode.setRowCount(0);
        for(pesanWA.Template t:pesanWA.DAFTAR){
            tabMode.addRow(new Object[]{t.judul,pesanWA.ambilTersimpan(t)==null?"Bawaan":"Diubah"});
        }
    }

    private void pilih(int baris){
        if(baris<0||baris>=pesanWA.DAFTAR.length){
            return;
        }
        pesanWA.Template t=pesanWA.DAFTAR[baris];
        if(t==dipilih){
            return;
        }
        if(!konfirmasiPerubahan()){
            // batal pindah, kembalikan pilihan ke template yang sedang diedit
            pindahBaris=true;
            int lama=indeks(dipilih);
            tbTemplate.setRowSelectionInterval(lama,lama);
            pindahBaris=false;
            return;
        }
        dipilih=t;
        // pilihan jenis surat hanya untuk template Kirim surat
        panelJenis.setVisible(t==pesanWA.SURAT);
        pilihJenis(0);
        jenisLama=0;
        muat(t);
    }

    /** Ubah pilihan combo jenis surat tanpa memicu pindah template. */
    private void pilihJenis(int idx){
        gantiJenis=true;
        CmbJenisSurat.setSelectedIndex(idx);
        gantiJenis=false;
    }

    /** Tampilkan template t (template di tabel, atau Kirim surat per jenis surat) di editor. */
    private void muat(pesanWA.Template t){
        aktif=t;
        LJudul.setText(t.judul);
        LPenanda.setText("<html>Penanda : "+t.penanda.replace("\n","<br>")+"</html>");
        panelPenanda.removeAll();
        for(String p:penanda(t)){
            widget.Button b=new widget.Button();
            b.setText(p);
            b.setToolTipText("Sisipkan "+p+" di posisi kursor");
            b.setPreferredSize(new Dimension(Math.max(60,p.length()*8+16),22));
            b.addActionListener(e -> {
                TIsi.replaceSelection(p);
                TIsi.requestFocus();
            });
            panelPenanda.add(b);
        }
        panelPenanda.revalidate();
        panelPenanda.repaint();
        isiAwal=pesanWA.ambil(t);
        TIsi.setText(isiAwal);
        TIsi.setCaretPosition(0);
        perbaruiStatus();
    }

    /** Status template yang sedang diedit di LStatus, dan status baris template di tabel. */
    private void perbaruiStatus(){
        if(aktif==null){
            return;
        }
        boolean diubah=pesanWA.ambilTersimpan(aktif)!=null;
        if(aktif.induk==null){
            LStatus.setText(diubah?"Template umum diubah":"Template umum bawaan");
            tabMode.setValueAt(diubah?"Diubah":"Bawaan",indeks(aktif),1);
        }else{
            LStatus.setText(diubah?"Teks khusus jenis ini":"Mengikuti template umum");
        }
    }

    /** Penanda {xxx} yang disebut di baris pertama keterangan template, untuk tombol sisip. */
    private Set<String> penanda(pesanWA.Template t){
        Set<String> hasil=new LinkedHashSet<>();
        Matcher m=Pattern.compile("\\{[a-z_]+\\}").matcher(t.penanda.split("\n")[0]);
        while(m.find()){
            hasil.add(m.group());
        }
        return hasil;
    }

    private int indeks(pesanWA.Template t){
        for(int i=0;i<pesanWA.DAFTAR.length;i++){
            if(pesanWA.DAFTAR[i]==t||(t!=null&&pesanWA.DAFTAR[i]==t.induk)){
                return i;
            }
        }
        return 0;
    }

    /** @return true bila boleh lanjut (tidak ada perubahan, sudah disimpan, atau perubahan dibuang) */
    private boolean konfirmasiPerubahan(){
        if(aktif==null||TIsi.getText().equals(isiAwal)){
            return true;
        }
        int pilihan=JOptionPane.showConfirmDialog(this,"Perubahan template \""+aktif.judul+"\" belum disimpan.\nSimpan sekarang?",
                "Konfirmasi",JOptionPane.YES_NO_CANCEL_OPTION);
        if(pilihan==JOptionPane.YES_OPTION){
            return simpan();
        }
        return pilihan==JOptionPane.NO_OPTION;
    }

    private boolean simpan(){
        if(aktif==null){
            return false;
        }
        if(TIsi.getText().trim().equals("")){
            JOptionPane.showMessageDialog(this,"Isi pesan masih kosong.");
            TIsi.requestFocus();
            return false;
        }
        try {
            pesanWA.simpan(aktif,TIsi.getText());
            isiAwal=TIsi.getText();
            perbaruiStatus();
            JOptionPane.showMessageDialog(this,"Template tersimpan dan langsung dipakai untuk pesan berikutnya.");
            return true;
        } catch (Exception e) {
            System.out.println("Notif : "+e);
            JOptionPane.showMessageDialog(this,"Gagal menyimpan template:\n"+e.getMessage());
            return false;
        }
    }

