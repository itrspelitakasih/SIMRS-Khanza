    private String provider(){
        return CmbProvider.getSelectedIndex()==1?AsistenAI.OLLAMA:AsistenAI.OPENROUTER;
    }

    /** Isi combo model yang bisa diketik; getSelectedItem baru terisi setelah editor di-commit. */
    private String model(){
        Object isi=CmbModel.getEditor().getItem();
        return isi==null?"":isi.toString().trim();
    }

    /** Daftar model dan status API key / alamat server mengikuti provider terpilih. */
    private void gantiProvider(String model){
        String p=provider();
        boolean ollama=p.equals(AsistenAI.OLLAMA);
        CmbModel.setModel(new DefaultComboBoxModel<Object>(ollama?AsistenAI.MODEL_OLLAMA:AsistenAI.MODEL_OPENROUTER));
        CmbModel.setSelectedItem(model==null?CmbModel.getItemAt(0):model);
        if(ollama){
            label1.setText("Server :");
            String url=koneksiDBAI.OLLAMAURL();
            LblKey.setText(url.equals("")?"<html>Belum diisi. Tambahkan OLLAMAURL (mis. http://192.168.1.10:11434) di setting/database-extra.xml</html>":
                    "<html>Dari database-extra.xml : "+url+"<br>Klik Tes Koneksi untuk mengambil daftar model di server</html>");
        }else{
            label1.setText("API Key :");
            // API key tidak pernah ditampilkan utuh
            String key=AsistenAI.apiKey(p);
            LblKey.setText(key.length()>12?"<html>Dari database-extra.xml : "+key.substring(0,7)+"..."+key.substring(key.length()-4)+"</html>":
                    "<html>Belum diisi. Tambahkan OPENROUTERAPIKEY di setting/database-extra.xml</html>");
        }
    }

    private void tampil(){
        lama=AsistenAI.baca(koneksi);
        CmbProvider.setSelectedIndex(lama.provider.equals(AsistenAI.OLLAMA)?1:0);
        gantiProvider(lama.model);
        CmbAktif.setSelectedItem(lama.aktif?"Yes":"No");
        TPrompt.setText(lama.systemPrompt);
        TPrompt.setCaretPosition(0);
    }
