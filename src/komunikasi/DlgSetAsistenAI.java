    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSimpanActionPerformed
        if(model().equals("")){
            JOptionPane.showMessageDialog(this,"Model belum diisi.");
            CmbModel.requestFocus();
            return;
        }
        AsistenAI.Setting s=new AsistenAI.Setting();
        s.provider=provider();
        s.model=model();
        s.systemPrompt=TPrompt.getText().trim();
        s.aktif=CmbAktif.getSelectedItem().equals("Yes");
        try {
            AsistenAI.simpan(koneksi,s);
            tersimpan=true;
            JOptionPane.showMessageDialog(this,"Setting Asisten AI tersimpan.");
            dispose();
        } catch (Exception e) {
            System.out.println("Notifikasi Asisten AI : "+e);
            JOptionPane.showMessageDialog(this,"Gagal menyimpan : "+e.getMessage());
        }
    }//GEN-LAST:event_BtnSimpanActionPerformed

    private void BtnTesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnTesActionPerformed
        final String provider=provider();
        // dibaca ulang supaya perubahan database-extra.xml langsung bisa dites tanpa menutup aplikasi
        boolean kosong=provider.equals(AsistenAI.OLLAMA)?koneksiDBAI.OLLAMAURL().equals(""):AsistenAI.apiKey(provider).equals("");
        if(kosong){
            JOptionPane.showMessageDialog(this,AsistenAI.pesanBelumDiisi(provider));
            return;
        }
        BtnTes.setEnabled(false);
        final List<String> modelServer=new ArrayList<>();
        new SwingWorker<String,Void>(){
            @Override
            protected String doInBackground(){
                return AsistenAI.tesKoneksi(provider,modelServer);
            }

            @Override
            protected void done(){
                BtnTes.setEnabled(true);
                // Ollama: isi daftar model dengan model yang benar-benar sudah di-pull di server
                if(!modelServer.isEmpty()&&provider().equals(provider)){
                    String dipilih=model();
                    CmbModel.setModel(new DefaultComboBoxModel<Object>(modelServer.toArray()));
                    CmbModel.setSelectedItem(modelServer.contains(dipilih)?dipilih:modelServer.get(0));
                }
                try {
                    JOptionPane.showMessageDialog(DlgSetAsistenAI.this,get());
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(DlgSetAsistenAI.this,"Gagal : "+e.getMessage());
                }
            }
        }.execute();
    }//GEN-LAST:event_BtnTesActionPerformed

