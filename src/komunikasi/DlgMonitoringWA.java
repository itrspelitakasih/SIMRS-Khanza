    private void BtnKirimUlangActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnKirimUlangActionPerformed
        int baris=barisTerpilih();
        if(baris<0){
            return;
        }
        String status=tabMode.getValueAt(baris,K_STATUS).toString();
        if(!status.equals("GAGAL")&&!status.equals("BATAL")){
            JOptionPane.showMessageDialog(this,"Hanya pesan berstatus GAGAL atau BATAL yang bisa dikirim ulang.");
            return;
        }
        String nowa=tabMode.getValueAt(baris,3).toString();
        if(JOptionPane.showConfirmDialog(this,"Kirim ulang pesan ke "+nowa+" ?\n\n"+
                "Pastikan nomor WA sudah benar. Nomor yang tidak terdaftar di WhatsApp akan gagal lagi.",
                "Kirim Ulang",JOptionPane.YES_NO_OPTION)!=JOptionPane.YES_OPTION){
            return;
        }
        ubahStatus(Long.parseLong(tabMode.getValueAt(baris,K_NOMOR).toString()),
                "UPDATE wa_outbox SET STATUS='ANTRIAN',SUCCESS=NULL,TANGGAL_JAM=NOW(),SENT_DATETIME=NULL,"+
                "RESPONSE='Dikirim ulang dari SIMRS' WHERE NOMOR=? AND STATUS IN ('GAGAL','BATAL')",true);
    }//GEN-LAST:event_BtnKirimUlangActionPerformed

