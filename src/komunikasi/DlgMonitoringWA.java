    private static final class WarnaStatus extends WarnaTable {
        @Override
        public Component getTableCellRendererComponent(JTable table, Object value, boolean isSelected, boolean hasFocus, int row, int column) {
            Component c=super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
            Color warna=new Color(50,50,50);
            if(table.convertColumnIndexToModel(column)==K_STATUS&&value!=null){
                switch(value.toString()){
                    case "TERKIRIM": warna=new Color(46,125,50); break;
                    case "ANTRIAN":
                    case "PROSES":   warna=new Color(230,126,0); break;
                    case "GAGAL":    warna=new Color(198,40,40); break;
                    case "BATAL":    warna=new Color(120,120,120); break;
                }
                c.setFont(c.getFont().deriveFont(Font.BOLD));
            }
            c.setForeground(warna);
            return c;
        }
    }

