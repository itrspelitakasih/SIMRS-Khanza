    /** Ambil pesan sesuai filter di background, lalu isi tabel & ringkasan. */
    public void tampil(){
        if(memuat){
            return;
        }
        memuat=true;
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        final String tgl1=tanggalSql(Tgl1.getDate()), tgl2=tanggalSql(Tgl2.getDate());
        final String status=CmbStatus.getSelectedItem()==null?"Semua":CmbStatus.getSelectedItem().toString();
        final String cari=TCari.getText().trim();
        new SwingWorker<Object[],Void>(){
            private String galat="";
            @Override
            protected Object[] doInBackground(){
                List<Object[]> baris=new ArrayList<>();
                List<String[]> isi=new ArrayList<>();
                int[] jumlah=new int[4];   // terkirim, antrian+proses, gagal, batal
                String sql="SELECT NOMOR,TANGGAL_JAM,SENT_DATETIME,NOWA,IFNULL(SOURCE,''),STATUS,PESAN,IFNULL(RESPONSE,''),IFNULL(SENDER,'') "+
                        "FROM wa_outbox WHERE DATE(IFNULL(TANGGAL_JAM,SENT_DATETIME)) BETWEEN ? AND ? "+
                        (status.equals("Semua")?"":"AND STATUS=? ")+
                        (cari.equals("")?"":"AND (NOWA LIKE ? OR PESAN LIKE ? OR SOURCE LIKE ? OR RESPONSE LIKE ?) ")+
                        "ORDER BY TANGGAL_JAM DESC,NOMOR DESC LIMIT 2000";
                try (Connection k=koneksiDBWa.newConnection();
                     PreparedStatement ps=k.prepareStatement(sql)){
                    int i=1;
                    ps.setString(i++,tgl1);
                    ps.setString(i++,tgl2);
                    if(!status.equals("Semua")){
                        ps.setString(i++,status);
                    }
                    if(!cari.equals("")){
                        for(int j=0;j<4;j++){
                            ps.setString(i++,"%"+cari+"%");
                        }
                    }
                    try (ResultSet rs=ps.executeQuery()){
                        while(rs.next()){
                            String pesan=nz(rs.getString(7)), respon=nz(rs.getString(8)), st=nz(rs.getString(6));
                            baris.add(new Object[]{
                                rs.getLong(1),waktu(rs.getString(2)),waktu(rs.getString(3)),nomorWA(rs.getString(4)),
                                rs.getString(5),st,ringkas(pesan),ringkas(respon),rs.getString(9)
                            });
                            isi.add(new String[]{pesan,respon});
                            switch(st){
                                case "TERKIRIM": jumlah[0]++; break;
                                case "ANTRIAN":
                                case "PROSES":   jumlah[1]++; break;
                                case "GAGAL":    jumlah[2]++; break;
                                case "BATAL":    jumlah[3]++; break;
                            }
                        }
                    }
                } catch (Exception e) {
                    galat=e.getMessage();
                    System.out.println("Notifikasi Monitoring WA : "+e);
                }
                return new Object[]{baris,isi,jumlah};
            }
            @Override
            @SuppressWarnings("unchecked")
            protected void done(){
                memuat=false;
                setCursor(Cursor.getDefaultCursor());
                try {
                    Object[] h=get();
                    tabMode.setRowCount(0);
                    detail.clear();
                    for(Object[] b:(List<Object[]>)h[0]){
                        tabMode.addRow(b);
                    }
                    detail.addAll((List<String[]>)h[1]);
                    int[] j=(int[])h[2];
                    LCount.setText(""+tabMode.getRowCount());
                    LRingkasan.setText("Terkirim : "+j[0]+"   |   Antrian : "+j[1]+"   |   Gagal : "+j[2]+"   |   Batal : "+j[3]);
                    tampilDetail();
                    if(!galat.equals("")){
                        JOptionPane.showMessageDialog(DlgMonitoringWA.this,"Gagal membaca data pesan WA :\n"+galat);
                    }
                } catch (Exception e) {
                    System.out.println("Notifikasi Monitoring WA : "+e);
                }
            }
        }.execute();
    }

    /** Jalankan update status satu pesan di background lalu muat ulang tabel. */
    private void ubahStatus(long nomor,String sql,boolean prosesAntrian){
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        new SwingWorker<Integer,Void>(){
            private String galat="";
            @Override
            protected Integer doInBackground(){
                try (Connection k=koneksiDBWa.newConnection();
                     PreparedStatement ps=k.prepareStatement(sql)){
                    ps.setLong(1,nomor);
                    int n=ps.executeUpdate();
                    if(n>0&&prosesAntrian){
                        GoWAService.processQueueNow();
                    }
                    return n;
                } catch (Exception e) {
                    galat=e.getMessage();
                    return 0;
                }
            }
            @Override
            protected void done(){
                setCursor(Cursor.getDefaultCursor());
                if(!galat.equals("")){
                    JOptionPane.showMessageDialog(DlgMonitoringWA.this,"Gagal mengubah status pesan :\n"+galat);
                }else{
                    try {
                        if(get()==0){
                            JOptionPane.showMessageDialog(DlgMonitoringWA.this,"Status pesan sudah berubah, data dimuat ulang.");
                        }
                    } catch (Exception e) {
                        System.out.println("Notifikasi Monitoring WA : "+e);
                    }
                }
                tampil();
            }
        }.execute();
    }

    /** Baris model yang dipilih, atau -1 (dengan pesan) bila belum ada. */
    private int barisTerpilih(){
        if(tbPesan.getSelectedRow()<0){
            JOptionPane.showMessageDialog(this,"Silahkan pilih pesan di tabel terlebih dahulu..!!");
            return -1;
        }
        return tbPesan.convertRowIndexToModel(tbPesan.getSelectedRow());
    }

    private void tampilDetail(){
        int v=tbPesan.getSelectedRow();
        if(v<0){
            TDetail.setText("");
            BtnKirimUlang.setEnabled(false);
            BtnBatalkan.setEnabled(false);
            return;
        }
        int m=tbPesan.convertRowIndexToModel(v);
        String status=tabMode.getValueAt(m,K_STATUS).toString();
        String[] d=m<detail.size()?detail.get(m):new String[]{"",""};
        TDetail.setText("Ke : "+tabMode.getValueAt(m,3)+"\nStatus : "+status+
                "\nJadwal : "+tabMode.getValueAt(m,1)+
                (tabMode.getValueAt(m,2).toString().equals("")?"":"\nTerkirim : "+tabMode.getValueAt(m,2))+
                "\n\n"+d[0]+(d[1].equals("")?"":"\n\n--- Keterangan ---\n"+d[1]));
        TDetail.setCaretPosition(0);
        BtnKirimUlang.setEnabled(status.equals("GAGAL")||status.equals("BATAL"));
        BtnBatalkan.setEnabled(status.equals("ANTRIAN"));
    }

    private static String tanggalSql(Date d){
        return new SimpleDateFormat("yyyy-MM-dd").format(d==null?new Date():d);
    }

    /** "2026-11-19 08:00:00.0" -> "2026-11-19 08:00:00" */
    private static String waktu(String s){
        return s==null?"":s.replaceAll("\\.0$","");
    }

    /** "6281234567890@c.us" -> "6281234567890" */
    private static String nomorWA(String s){
        return s==null?"":s.replaceAll("@.*$","");
    }

    private static String ringkas(String s){
        String satuBaris=s.replaceAll("\\s+"," ").trim();
        return satuBaris.length()>150?satuBaris.substring(0,150)+"...":satuBaris;
    }

    private static String nz(String s){
        return s==null?"":s;
    }
