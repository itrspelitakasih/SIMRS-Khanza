    private double angka(Object v) {
        try { return Double.parseDouble(v.toString().replace(".", "").replace(",", ".")); } catch (Exception e) { return 0; }
    }

    /** Perubahan centang di salah satu tabel. */
    private void centang(DefaultTableModel tm, javax.swing.event.TableModelEvent e, String jenis) {
        if (memuat || e.getColumn() != 0 || e.getFirstRow() < 0) return;
        int r = e.getFirstRow();
        boolean on = Boolean.TRUE.equals(tm.getValueAt(r, 0));
        String k = tm.getValueAt(r, 1).toString();
        int kolomTarif = 5;
        double t = angka(tm.getValueAt(r, kolomTarif));
        switch (jenis) {
            case "T": if (on) selTindakan.add(k); else selTindakan.remove(k); tarif.put("T:" + k, t); break;
            case "R": if (on) selRad.add(k); else selRad.remove(k); tarif.put("R:" + k, t); break;
            case "L":
                if (on) selLab.add(k); else { selLab.remove(k); selItem.removeIf(s -> s.startsWith(k + "#")); }
                tarif.put("L:" + k, t);
                javax.swing.SwingUtilities.invokeLater(this::tampilItem);
                break;
            case "I": {
                // kolom item: P, Kode Lab, Id, Item, Satuan, Biaya Item; baris judul grup = Id kosong
                String lk = k, id = tm.getValueAt(r, 2).toString();
                if (id.equals("")) { setLab(lk, on); javax.swing.SwingUtilities.invokeLater(this::tampilItem); break; }
                String kunci = lk + "#" + id;
                if (on) {
                    selItem.add(kunci);
                    if (!selLab.contains(lk)) { setLab(lk, true); javax.swing.SwingUtilities.invokeLater(this::tampilItem); }
                } else {
                    if (selLab.contains(lk) && !adaItemDipilih(lk)) {
                        // semula "semua item" (tanpa pilihan): jadikan pilihan eksplisit semua item kecuali yang dilepas
                        for (int i = 0; i < tmItem.getRowCount(); i++) {
                            String lk2 = tmItem.getValueAt(i, 1).toString(), id2 = tmItem.getValueAt(i, 2).toString();
                            if (lk2.equals(lk) && !id2.equals("") && !id2.equals(id)) { selItem.add(lk + "#" + id2); tarif.put("I:" + lk + "#" + id2, angka(tmItem.getValueAt(i, 5))); }
                        }
                    } else selItem.remove(kunci);
                    // semua item dilepas = pemeriksaan keluar dari paket
                    if (!adaItemDipilih(lk) && selLab.contains(lk)) { setLab(lk, false); javax.swing.SwingUtilities.invokeLater(this::tampilItem); }
                }
                tarif.put("I:" + kunci, angka(tm.getValueAt(r, 5)));
                break;
            }
        }
        hitung();
    }

    private void hitung() {
        double jml = 0;
        for (String k : selTindakan) jml += tarif.getOrDefault("T:" + k, 0d);
        for (String k : selLab) jml += tarif.getOrDefault("L:" + k, 0d);
        for (String k : selItem) jml += tarif.getOrDefault("I:" + k, 0d);
        for (String k : selRad) jml += tarif.getOrDefault("R:" + k, 0d);
        double h = angka(Harga.getText());
        String s = "Isi paket: " + selTindakan.size() + " tindakan, " + selLab.size() + " pemeriksaan lab" + (selLab.isEmpty() ? "" : " (" + (selItem.isEmpty() ? "semua item" : selItem.size() + " item dipilih") + ")") + ", " + selRad.size() + " radiologi"
                + "   |   Jumlah tarif item: Rp " + rp(jml);
        if (h > 0) s += "   |   Harga paket: Rp " + rp(h) + "   |   " + (h < jml ? "Potongan Rp " + rp(jml - h) : (h > jml ? "Tambahan Rp " + rp(h - jml) : "pas"));
        LInfo.setText(s);
        sinkronSemuaItem();
    }

