    private void muatPilihan(String sql, String k, String jenis) throws Exception {
        try (PreparedStatement ps = koneksi.prepareStatement(sql)) {
            ps.setString(1, k);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    String v = rs.getString(1);
                    switch (jenis) { case "T": selTindakan.add(v); break; case "L": selLab.add(v); break; case "I": selItem.add(v); break; default: selRad.add(v); }
                    tarif.put(jenis + ":" + v, rs.getDouble(2));
                }
            }
        }
    }

    private void simpan() {
        if (!PaketTindakan.aktif()) { JOptionPane.showMessageDialog(this, "Tabel Paket Tindakan belum tersedia di database."); return; }
        String k = Kode.getText().trim(), n = Nama.getText().trim();
        double h = angka(Harga.getText());
        if (k.equals("") || n.equals("")) { JOptionPane.showMessageDialog(this, "Kode dan nama paket wajib diisi."); return; }
        if (k.length() > 10) { JOptionPane.showMessageDialog(this, "Kode paket maksimal 10 karakter."); return; }
        if (h <= 0) { JOptionPane.showMessageDialog(this, "Harga paket wajib diisi."); return; }
        if (selTindakan.isEmpty() && selLab.isEmpty() && selRad.isEmpty()) { JOptionPane.showMessageDialog(this, "Pilih minimal satu tindakan, pemeriksaan lab, atau radiologi."); return; }
        pulihkanItemTunggu();
        if (!itemTunggu.isEmpty()) {
            JOptionPane.showMessageDialog(this, itemTunggu.size() + " pemeriksaan lab hanya memakai sebagian item, tetapi templatenya belum ada di jenis bayar ini.\n"
                    + "Klik Salin Template dulu supaya pilihan itemnya tidak hilang, lalu Simpan.");
            return;
        }
        try {
            koneksi.setAutoCommit(false);
            exec("insert into paket_tindakan values (?,?,?) on duplicate key update nama_paket=values(nama_paket),harga=values(harga)", k, n, h);
            exec("delete from paket_tindakan_tindakan where kode_paket=?", k);
            exec("delete from paket_tindakan_lab where kode_paket=?", k);
            exec("delete from paket_tindakan_radiologi where kode_paket=?", k);
            for (String t : selTindakan) exec("insert into paket_tindakan_tindakan values (?,?)", k, t);
            for (String l : selLab) {
                boolean adaItem = false;
                for (String it : selItem) if (it.startsWith(l + "#")) { exec("insert into paket_tindakan_lab values (?,?,?)", k, l, Integer.valueOf(it.substring(l.length() + 1))); adaItem = true; }
                if (!adaItem) exec("insert into paket_tindakan_lab values (?,?,0)", k, l);
            }
            for (String r : selRad) exec("insert into paket_tindakan_radiologi values (?,?)", k, r);
            koneksi.commit();
            LJenisBayar.setText("");
            JOptionPane.showMessageDialog(this, "Paket " + n + " tersimpan." + (belumTemplate.isEmpty() ? "" : "\n\nPerhatian: " + belumTemplate.size()
                    + " pemeriksaan lab belum punya template, hasilnya belum bisa diisi petugas lab.\nGunakan Salin Template Dari di tab Laboratorium."));
            tampilPaket();
            Kode.setEditable(false);
        } catch (Exception e) {
            try { koneksi.rollback(); } catch (Exception ex) { }
            JOptionPane.showMessageDialog(this, "Gagal menyimpan paket: " + e.getMessage());
        } finally {
            try { koneksi.setAutoCommit(true); } catch (Exception ex) { }
        }
    }

    private void exec(String sql, Object... v) throws Exception {
        try (PreparedStatement ps = koneksi.prepareStatement(sql)) {
            for (int i = 0; i < v.length; i++) ps.setObject(i + 1, v[i]);
            ps.executeUpdate();
        }
    }

