    private void BtnAktifkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnAktifkanActionPerformed
        int baris=barisTerpilih();
        if(baris<0){
            return;
        }
        String nama=tbAutoSign.getValueAt(baris,1).toString(), email=tbAutoSign.getValueAt(baris,2).toString();
        if(email.isEmpty()){
            JOptionPane.showMessageDialog(this,"Email "+nama+" belum diisi di master dokter.");
            return;
        }
        if(tbAutoSign.getValueAt(baris,KOLOM_STATUS_AUTOSIGN).toString().equals("Aktif")){
            JOptionPane.showMessageDialog(this,"Auto sign "+nama+" sudah aktif.");
            return;
        }
        if(pengirim.isEmpty()){
            JOptionPane.showMessageDialog(this,"Akun pengirim MekariSign belum terbaca, klik tombol cari terlebih dahulu.");
            return;
        }
        if(JOptionPane.showConfirmDialog(this,
                "Aktifkan auto sign untuk "+nama+" ("+email+") ?\n\n"+
                "Semua dokumen dari SIMRS untuk dokter ini akan langsung ditandatangani\n"+
                "dengan tanda tangan tersimpannya, TANPA dibaca ulang oleh dokter.\n"+
                "Pastikan sudah ada persetujuan dari dokter yang bersangkutan.",
                "Konfirmasi Auto Sign",JOptionPane.YES_NO_OPTION)!=JOptionPane.YES_OPTION){
            return;
        }
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            MekariSignApi.aktifkanAutoSign(pengirim,email);
            setCursor(Cursor.getDefaultCursor());
            JOptionPane.showMessageDialog(this,"Auto sign "+nama+" aktif.");
            tampil();
        } catch (Exception e) {
            setCursor(Cursor.getDefaultCursor());
            tampilGalat(e,"\n\nPastikan "+email+" sudah terdaftar & terkonfirmasi di MekariSign\ndan sudah menyimpan tanda tangan di akunnya.");
        }
    }//GEN-LAST:event_BtnAktifkanActionPerformed

    private void BtnNonaktifkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnNonaktifkanActionPerformed
        int baris=barisTerpilih();
        if(baris<0){
            return;
        }
        String nama=tbAutoSign.getValueAt(baris,1).toString(), id=tbAutoSign.getValueAt(baris,KOLOM_ID_AUTOSIGN).toString();
        if(id.isEmpty()){
            JOptionPane.showMessageDialog(this,"Auto sign "+nama+" memang tidak aktif.");
            return;
        }
        if(JOptionPane.showConfirmDialog(this,"Matikan auto sign untuk "+nama+" ?\nDokumen berikutnya akan dikirim sebagai undangan tanda tangan biasa.",
                "Konfirmasi",JOptionPane.YES_NO_OPTION)!=JOptionPane.YES_OPTION){
            return;
        }
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            MekariSignApi.hapusAutoSign(id);
            setCursor(Cursor.getDefaultCursor());
            JOptionPane.showMessageDialog(this,"Auto sign "+nama+" dimatikan.");
            tampil();
        } catch (Exception e) {
            setCursor(Cursor.getDefaultCursor());
            tampilGalat(e,"");
        }
    }//GEN-LAST:event_BtnNonaktifkanActionPerformed

    private void BtnEkycActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEkycActionPerformed
        int baris=barisTerpilih();
        if(baris<0){
            return;
        }
        String nama=tbAutoSign.getValueAt(baris,1).toString(), email=tbAutoSign.getValueAt(baris,2).toString();
        if(email.isEmpty()){
            JOptionPane.showMessageDialog(this,"Email "+nama+" belum diisi di master dokter.");
            return;
        }
        MekariSignApi.Ekyc lama=ekyc.get(email.toLowerCase());
        String status=lama==null?"":lama.status;
        if(status.equals("success")){
            JOptionPane.showMessageDialog(this,nama+" sudah terverifikasi eKYC dan memiliki sertifikat PSrE aktif.");
            return;
        }
        if(status.equals("not_started")||status.equals("verifying")){
            JOptionPane.showMessageDialog(this,nama+" sudah diundang eKYC (status : "+MekariSignApi.keteranganEkyc(status)+").\n"+
                "Minta dokter membuka email undangan dari Mekari di "+email+" dan menyelesaikan verifikasinya.");
            return;
        }
        if(JOptionPane.showConfirmDialog(this,
                "Kirim undangan eKYC ke "+nama+" ("+email+") ?\n\n"+
                "Mekari akan mengirim email berisi link verifikasi identitas (KTP & swafoto)\n"+
                "untuk penerbitan sertifikat tanda tangan PSrE atas nama dokter.\n"+
                "Undangan ini memakai 1 kuota eKYC.",
                "Konfirmasi eKYC",JOptionPane.YES_NO_OPTION)!=JOptionPane.YES_OPTION){
            return;
        }
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            MekariSignApi.undangEkyc(email);
            setCursor(Cursor.getDefaultCursor());
            JOptionPane.showMessageDialog(this,"Undangan eKYC terkirim ke "+email+".\nStatus akan berubah menjadi Terverifikasi setelah dokter menyelesaikan verifikasi.");
            tampil();
        } catch (Exception e) {
            setCursor(Cursor.getDefaultCursor());
            tampilGalat(e,"");
        }
    }//GEN-LAST:event_BtnEkycActionPerformed

