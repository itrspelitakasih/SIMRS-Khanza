    /** Gabungkan master dokter aktif dengan daftar auto sign & eKYC di MekariSign. */
    public void tampil(){
        tabMode.setRowCount(0);
        LCount.setText("0");
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        Map<String,MekariSignApi.AutoSign> aktif=new HashMap<>();
        try {
            MekariSignApi.Profil p=MekariSignApi.profil();
            pengirim=p.email;
            LPengirim.setText("Pengirim : "+pengirim+"   |   Sisa kuota eKYC : "+p.kuotaEkyc);
            List<MekariSignApi.AutoSign> daftar=MekariSignApi.daftarAutoSign();
            for (MekariSignApi.AutoSign a : daftar) {
                if(a.docMakerEmail.equalsIgnoreCase(pengirim)){
                    aktif.put(a.signerEmail.toLowerCase(),a);
                }
            }
        } catch (Exception e) {
            setCursor(Cursor.getDefaultCursor());
            tampilGalat(e,"");
            return;
        }
        // eKYC dipisah: bila fitur eKYC belum diaktifkan untuk RS (403), auto sign tetap tampil
        try {
            ekyc=MekariSignApi.daftarEkyc();
        } catch (Exception e) {
            ekyc=new HashMap<>();
            System.out.println("Notifikasi MekariSign : daftar eKYC "+e);
        }
        String cari="%"+TCari.getText().trim()+"%";
        Set<String> tampilEmail=new HashSet<>();
        try (PreparedStatement ps=koneksi.prepareStatement(
                "select kd_dokter,nm_dokter,email from dokter where status='1' and (kd_dokter like ? or nm_dokter like ? or email like ?) order by nm_dokter")) {
            ps.setString(1,cari);
            ps.setString(2,cari);
            ps.setString(3,cari);
            try (ResultSet rs=ps.executeQuery()) {
                while(rs.next()){
                    String email=rs.getString("email")==null?"":rs.getString("email").trim();
                    MekariSignApi.AutoSign a=aktif.get(email.toLowerCase());
                    if(a!=null){
                        tampilEmail.add(email.toLowerCase());
                    }
                    tabMode.addRow(baris(rs.getString("kd_dokter"),rs.getString("nm_dokter"),email,a,email.isEmpty()));
                }
            }
        } catch (Exception e) {
            System.out.println("Notifikasi MekariSign : "+e);
        }
        // auto sign di Mekari yang emailnya tidak cocok dengan dokter aktif mana pun tetap ditampilkan supaya bisa dimatikan
        if(TCari.getText().trim().isEmpty()){
            for (MekariSignApi.AutoSign a : aktif.values()) {
                if(!tampilEmail.contains(a.signerEmail.toLowerCase())){
                    tabMode.addRow(baris("-","(bukan dokter aktif SIMRS)",a.signerEmail,a,false));
                }
            }
        }
        LCount.setText(""+tabMode.getRowCount());
        setCursor(Cursor.getDefaultCursor());
    }

    private Object[] baris(String kode,String nama,String email,MekariSignApi.AutoSign a,boolean emailKosong){
        MekariSignApi.Ekyc k=emailKosong?null:ekyc.get(email.toLowerCase());
        return new Object[]{
            kode,nama,email,
            emailKosong?"Email kosong":(a==null?"Tidak":"Aktif"),
            a==null?"":waktu(a.dibuat),
            emailKosong?"-":MekariSignApi.keteranganEkyc(k==null?"":k.status),
            k==null?"":waktu(k.diupdate),
            a==null?"":a.id
        };
    }

    /** 2026-11-06T07:22:29.073Z (UTC) -> jam lokal PC, mis. 2026-11-06 15:22:29 */
    private static String waktu(String iso){
        if(iso==null||iso.isEmpty()){
            return "";
        }
        try {
            return java.time.format.DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")
                    .format(java.time.Instant.parse(iso).atZone(java.time.ZoneId.systemDefault()));
        } catch (Exception e) {
            return iso.replace("T"," ").replaceAll("\\..*$","");
        }
    }

    private int barisTerpilih(){
        if(tbAutoSign.getSelectedRow()<0){
            JOptionPane.showMessageDialog(this,"Silahkan pilih dokter terlebih dahulu..!!");
            return -1;
        }
        return tbAutoSign.getSelectedRow();
    }

    private void tampilGalat(Exception e,String saran){
        System.out.println("Notifikasi MekariSign : "+e);
        JOptionPane.showMessageDialog(this,(e instanceof MekariSignApi.MekariSignException?e.getMessage():"Gagal menghubungi MekariSign : "+e.getMessage())+saran);
    }
