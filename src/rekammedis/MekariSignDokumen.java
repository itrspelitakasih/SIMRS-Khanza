    private void BtnStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnStatusActionPerformed
        int baris=barisTerpilih();
        if(baris<0){
            return;
        }
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            MekariSignApi.Dokumen d=MekariSignApi.cek(tbDokumen.getValueAt(baris,K_ID).toString(),tbDokumen.getValueAt(baris,K_EMAIL).toString());
            tbDokumen.setValueAt(keterangan(d.status),baris,K_STATUS);
            setCursor(Cursor.getDefaultCursor());
            JOptionPane.showMessageDialog(this,"Status tanda tangan : "+keterangan(d.status));
        } catch (Exception e) {
            setCursor(Cursor.getDefaultCursor());
            tampilGalat(e);
        }
    }//GEN-LAST:event_BtnStatusActionPerformed

    private void BtnTTDActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnTTDActionPerformed
        int baris=barisTerpilih();
        if(baris<0){
            return;
        }
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            MekariSignApi.Dokumen d=MekariSignApi.cek(tbDokumen.getValueAt(baris,K_ID).toString(),tbDokumen.getValueAt(baris,K_EMAIL).toString());
            tbDokumen.setValueAt(keterangan(d.status),baris,K_STATUS);
            setCursor(Cursor.getDefaultCursor());
            if(!d.status.equals("in_progress")){
                JOptionPane.showMessageDialog(this,"Dokumen tidak menunggu tanda tangan lagi.\nStatus : "+keterangan(d.status));
            }else if(d.signingUrl.isEmpty()){
                JOptionPane.showMessageDialog(this,"Link tanda tangan tidak tersedia.\nSilahkan buka undangan tanda tangan di email "+tbDokumen.getValueAt(baris,K_EMAIL)+" atau aplikasi MekariSign.");
            }else{
                Desktop.getDesktop().browse(new URI(d.signingUrl));
            }
        } catch (Exception e) {
            setCursor(Cursor.getDefaultCursor());
            tampilGalat(e);
        }
    }//GEN-LAST:event_BtnTTDActionPerformed

    private void BtnDownloadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnDownloadActionPerformed
        int baris=barisTerpilih();
        if(baris<0){
            return;
        }
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            String id=tbDokumen.getValueAt(baris,K_ID).toString();
            MekariSignApi.Dokumen d=MekariSignApi.cek(id,tbDokumen.getValueAt(baris,K_EMAIL).toString());
            tbDokumen.setValueAt(keterangan(d.status),baris,K_STATUS);
            if(!d.status.equals("completed")){
                setCursor(Cursor.getDefaultCursor());
                JOptionPane.showMessageDialog(this,"Dokumen belum selesai ditandatangani.\nStatus : "+keterangan(d.status));
                return;
            }
            File tujuan=new File("TTE"+tbDokumen.getValueAt(baris,K_FILE).toString().replaceAll("[\\\\/:*?\"<>|]","").replaceAll("(?i)\\.pdf$","")+".pdf");
            MekariSignApi.download(id,tujuan);
            setCursor(Cursor.getDefaultCursor());
            System.out.println("Download MekariSign Selesai : "+tujuan.getAbsolutePath());
            Desktop.getDesktop().browse(tujuan.toURI());
        } catch (Exception e) {
            setCursor(Cursor.getDefaultCursor());
            tampilGalat(e);
        }
    }//GEN-LAST:event_BtnDownloadActionPerformed

    private void BtnCekSemuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnCekSemuaActionPerformed
        String menunggu=keterangan("in_progress");
        int dicek=0, selesai=0, gagal=0;
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        for (int i = 0; i < tbDokumen.getRowCount(); i++) {
            if(!tbDokumen.getValueAt(i,K_STATUS).toString().equals(menunggu)){
                continue;
            }
            dicek++;
            try {
                MekariSignApi.Dokumen d=MekariSignApi.cek(tbDokumen.getValueAt(i,K_ID).toString(),tbDokumen.getValueAt(i,K_EMAIL).toString());
                tbDokumen.setValueAt(keterangan(d.status),i,K_STATUS);
                if(d.status.equals("completed")){
                    selesai++;
                }
            } catch (Exception e) {
                gagal++;
                System.out.println("Notifikasi MekariSign : cek "+tbDokumen.getValueAt(i,K_ID)+" "+e);
            }
        }
        setCursor(Cursor.getDefaultCursor());
        if(dicek==0){
            JOptionPane.showMessageDialog(this,"Tidak ada dokumen yang menunggu tanda tangan di daftar ini.");
        }else{
            JOptionPane.showMessageDialog(this,dicek+" dokumen dicek, "+selesai+" sudah selesai ditandatangani"+
                (gagal>0?", "+gagal+" gagal dicek (lihat log)":"")+".");
            tampil();
        }
    }//GEN-LAST:event_BtnCekSemuaActionPerformed

