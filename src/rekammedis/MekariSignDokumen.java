    public static String keterangan(String status){
        switch (status==null?"":status) {
            case "in_progress": return "Menunggu tanda tangan";
            case "completed": return "Selesai ditandatangani";
            case "voided": return "Dibatalkan pengirim";
            case "declined": return "Ditolak penandatangan";
            case "denied": return "Ditolak PSrE (verifikasi identitas gagal)";
            default: return status==null||status.isEmpty()?"-":status;
        }
    }

    /**
     * Kirim PDF ke MekariSign (tanda tangan di keyword #1A) lalu buka modul ini pada dokumen tsb.
     * Dipanggil dari form pembuat dokumen.
     */
    public static void kirimDanTampilkan(java.awt.Component induk,File pdf,String noRawat,String jenisDokumen,
                                         String kdDokter,String namaDokter,String email){
        kirimDanTampilkan(induk,pdf,noRawat,jenisDokumen,kdDokter,namaDokter,email,
                jenisDokumen.replaceAll("[^A-Za-z0-9]","")+"_"+noRawat.replaceAll("/","")+"_"+
                new java.text.SimpleDateFormat("yyyyMMddHHmmss").format(new Date()));
    }

    /**
     * Nama file untuk Riwayat Perawatan dsb: NoRawat_NoRM_NamaPasien (tanpa garis miring/karakter terlarang).
     */
    public static String namaFilePasien(String noRawat,String noRM,String namaPasien){
        return (noRawat.replaceAll("/","")+"_"+noRM.trim()+"_"+namaPasien.trim())
                .replaceAll("[\\\\/:*?\"<>|]","").replaceAll("\\s+"," ");
    }

    /**
     * Nama file harus unik di MekariSign selama dokumen lama belum dibatalkan/ditolak (422 bila bentrok).
     * Bila nama dasar sudah dipakai dokumen yang masih berlaku, ditambah akhiran _2, _3, dst.
     */
    private static String namaFileUnik(String namaDasar){
        Connection koneksi=koneksiDB.condb();
        MekariSignApi.siapkanTabel(koneksi);
        for (int ke = 1; ke < 100; ke++) {
            String nama=namaDasar+(ke==1?"":"_"+ke)+".pdf";
            try (PreparedStatement ps=koneksi.prepareStatement(
                    "select count(*) from mekarisign_dokumen where nama_file=? and status not in ('voided','declined')")) {
                ps.setString(1,nama);
                try (ResultSet rs=ps.executeQuery()) {
                    if(rs.next()&&rs.getInt(1)==0){
                        return nama;
                    }
                }
            } catch (Exception e) {
                System.out.println("Notifikasi MekariSign : cek nama file "+e);
                return nama;
            }
        }
        return namaDasar+"_"+new java.text.SimpleDateFormat("yyyyMMddHHmmss").format(new Date())+".pdf";
    }

    /** Sama seperti di atas dengan nama file ditentukan pemanggil (tanpa .pdf). */
    public static void kirimDanTampilkan(java.awt.Component induk,File pdf,String noRawat,String jenisDokumen,
                                         String kdDokter,String namaDokter,String email,String namaDasar){
        String namaFile=namaFileUnik(namaDasar);
        induk.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            MekariSignApi.Dokumen d=MekariSignApi.kirim(pdf,namaFile,noRawat,jenisDokumen,kdDokter,namaDokter,email);
            System.out.println("Dokumen MekariSign terkirim : "+d.id+" "+d.namaFile);
            // Dokter dengan auto sign langsung ditandatangani Mekari dalam beberapa detik:
            // cek status sebentar supaya pesan yang tampil sesuai kenyataan (tanpa setting apa pun).
            String statusAkhir=d.status;
            for (int i = 0; i < 4 && "in_progress".equals(statusAkhir); i++) {
                Thread.sleep(1500);
                try {
                    statusAkhir=MekariSignApi.cek(d.id,email).status;
                } catch (Exception e) {
                    System.out.println("Notifikasi MekariSign : cek status setelah kirim "+e);
                    break;
                }
            }
            final boolean otomatis="completed".equals(statusAkhir);
            induk.setCursor(Cursor.getDefaultCursor());
            // Form pemanggil (Resume/Riwayat) adalah dialog modal: jendela ini harus modal juga,
            // kalau tidak ia diblokir dan tenggelam di belakang form pemanggil.
            MekariSignDokumen dlg=new MekariSignDokumen(null,true);
            dlg.setNoRawat(noRawat);
            dlg.pilih(d.id);
            dlg.setLocationRelativeTo(induk);
            // pesan dijalankan setelah jendela tampil (setVisible modal menahan sampai jendela ditutup)
            javax.swing.SwingUtilities.invokeLater(() -> {
                try {
                    if(otomatis){
                        JOptionPane.showMessageDialog(dlg,"Dokumen sudah ditandatangani otomatis (auto sign) oleh "+namaDokter+
                            ".\nKlik Download & Buka untuk melihat hasilnya.");
                    }else if(!d.signingUrl.isEmpty()){
                        int jawab=JOptionPane.showConfirmDialog(dlg,"Dokumen terkirim ke MekariSign.\nBuka halaman tanda tangan sekarang?","Konfirmasi",JOptionPane.YES_NO_OPTION);
                        if(jawab==JOptionPane.YES_OPTION){
                            Desktop.getDesktop().browse(new URI(d.signingUrl));
                        }
                    }else{
                        JOptionPane.showMessageDialog(dlg,"Dokumen terkirim ke MekariSign.\nUndangan tanda tangan dikirim ke email "+email+
                            ".\nSilahkan buka email tersebut untuk menandatangani, lalu klik Cek Status.");
                    }
                } catch (Exception e) {
                    System.out.println("Notifikasi MekariSign : "+e);
                }
            });
            dlg.setVisible(true);
        } catch (Exception e) {
            induk.setCursor(Cursor.getDefaultCursor());
            System.out.println("Notifikasi MekariSign : "+e);
            JOptionPane.showMessageDialog(null,e instanceof MekariSignApi.MekariSignException?e.getMessage():"Gagal mengirim ke MekariSign : "+e.getMessage());
        }
    }
