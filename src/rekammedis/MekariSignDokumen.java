    public void tampil(){
        Valid.tabelKosong(tabMode);
        String filterStatus;
        switch (CmbStatus.getSelectedIndex()) {
            case 1: filterStatus="m.status='in_progress' and "; break;
            case 2: filterStatus="m.status='completed' and "; break;
            case 3: filterStatus="m.status in ('voided','declined','denied') and "; break;
            default: filterStatus="";
        }
        String sql="select m.no_rawat,ifnull(r.no_rkm_medis,''),ifnull(p.nm_pasien,''),m.jenis_dokumen,m.nama_file,m.kd_dokter,m.email,"+
                   "m.kategori,m.tgl_kirim,m.status,m.tgl_update,m.id_dokumen "+
                   "from mekarisign_dokumen m left join reg_periksa r on r.no_rawat=m.no_rawat "+
                   "left join pasien p on p.no_rkm_medis=r.no_rkm_medis where "+
                   (noRawat.isEmpty()?"m.tgl_kirim between ? and ? and ":"m.no_rawat=? and ")+filterStatus+
                   "(m.no_rawat like ? or r.no_rkm_medis like ? or p.nm_pasien like ? or m.jenis_dokumen like ? or "+
                   "m.nama_file like ? or m.kd_dokter like ? or m.email like ?) "+
                   "order by m.tgl_kirim desc";
        try (PreparedStatement ps=koneksi.prepareStatement(sql)) {
            int i=1;
            if(noRawat.isEmpty()){
                ps.setString(i++,Valid.SetTgl(Tgl1.getSelectedItem()+"")+" 00:00:00");
                ps.setString(i++,Valid.SetTgl(Tgl2.getSelectedItem()+"")+" 23:59:59");
            }else{
                ps.setString(i++,noRawat);
            }
            String cari="%"+(noRawat.isEmpty()?TCari.getText().trim():"")+"%";
            for (int j = 0; j < 7; j++) {
                ps.setString(i++,cari);
            }
            try (ResultSet rs=ps.executeQuery()) {
                while(rs.next()){
                    tabMode.addRow(new Object[]{
                        rs.getString(1),rs.getString(2),rs.getString(3),rs.getString(4),rs.getString(5),rs.getString(6),
                        rs.getString(7),rs.getString(8),rs.getString(9),keterangan(rs.getString(10)),rs.getString(11),rs.getString(12)
                    });
                }
            }
        } catch (Exception e) {
            System.out.println("Notifikasi MekariSign : "+e);
        }
        LCount.setText(""+tabMode.getRowCount());
    }

